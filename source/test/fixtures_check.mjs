// 架空PDFで、修正前(src_before)と修正後(src)の解析結果を比べる
import {createRequire} from 'module';const require=createRequire(import.meta.url);
import {loadPages} from './load.mjs';
const SRC=process.argv[2]||'../src';
const P=require(SRC+'/parser.js');globalThis.MeetParser=P;
delete require.cache[require.resolve(SRC+'/logic.js')];const L=require(SRC+'/logic.js');
const F='fixtures/';let pass=0,fail=0;const ok=(c,m)=>{if(c){pass++;console.log('  ok',m)}else{fail++;console.log('  NG',m)}};
const sl=async f=>P.parseStartList(await loadPages(F+f)), tt=async f=>P.parseTimetable(await loadPages(F+f));
const rows=(s,t,day)=>{let r=L.build(s,t&&day?t.filter(x=>!x.date||x.date===day):t,['架空第一高'],{});return day?r.filter(x=>!x.date||x.date===day):r;};
console.log('[1] 見出しの継承');
let s=await sl('f1_small_heading.pdf');
const p2=s.entries.filter(e=>e.page===2);
ok(p2.length>0&&p2.every(e=>/200m/.test(e.event)),'2ページ目の出場者は200m（'+[...new Set(p2.map(e=>e.event))].join(',')+'）');
ok(s.warnings.length>0,'警告あり（問題なしにならない）：'+s.warnings.map(w=>'p.'+w.page+' '+w.warn.join('・')).join(' / '));
s=await sl('f1b_no_heading.pdf');
ok(s.warnings.some(w=>w.page===1),'見出しの無い番号の行に警告：'+s.warnings.map(w=>'p.'+w.page+' '+w.warn.join('・')).join(' / '));
console.log('[2] 決勝の時刻');
s=await sl('f2_program_final.pdf');
let R=rows(s,null);
const fin=R.filter(r=>/100m/.test(r.event));
ok(fin.length&&fin.every(r=>!r.start&&/時刻未確定/.test(r.note)),'プログラム：決勝に予選の09:00を流用しない（'+(fin[0]&&fin[0].start)+' / '+(fin[0]&&fin[0].note)+'）');
const h200=R.filter(r=>/200m/.test(r.event));
ok(h200.length&&h200.every(r=>r.start==='10:00'),'プログラム：200m予選は10:00（予選・決勝の2行から予選を選ぶ）');
s=await sl('f2b_sl_final.pdf');let T=await tt('f2b_tt_heatonly.pdf');R=rows(s,T);
ok(R.length&&R.every(r=>!r.start&&/時刻未確定/.test(r.note)),'タイムテーブル：決勝に予選の時刻を入れない（'+R[0].start+' / '+R[0].note+'）');
console.log('[3] 組ごとの時刻');
s=await sl('f3_sl_heats.pdf');
const heatTime=(T)=>{const o={};rows(s,T).forEach(r=>{o[r.heat]=r.start||'未確定'});return o;};
let ht=heatTime(await tt('f3_tt_from2.pdf'));console.log('   2組から:',JSON.stringify(ht));
ok(ht[1]==='未確定'&&ht[2]==='09:10'&&ht[3]==='09:20'&&ht[4]==='09:30','2組09:10・3組09:20・4組09:30、1組は未確定');
ht=heatTime(await tt('f3_tt_gap.pdf'));console.log('   欠番:',JSON.stringify(ht));
ok(ht[1]==='09:00'&&ht[2]==='未確定'&&ht[3]==='09:20'&&ht[4]==='09:30','欠番（2組なし）：1組09:00・2組未確定・3組09:20・4組09:30');
ht=heatTime(await tt('f3_tt_all.pdf'));console.log('   全4組:',JSON.stringify(ht));
ok(ht[1]==='09:00'&&ht[4]==='09:00','「全4組」は組番号として扱わない（全組の開始時刻）');
console.log('[4] 複数日');
s=await sl('f4_sl_twodays.pdf');T=await tt('f4_tt_twodays.pdf');
ok(s.multiDay&&s.dates.join(',')==='10/11,10/12','別ページの日付で複数日と判定（'+s.dates+'）');
ok(T.map(x=>x.date).join(',')==='10/11,10/12','タイムテーブルにも日付（'+T.map(x=>x.date)+'）');
const d1=rows(s,T,'10/11'),d2=rows(s,T,'10/12');
ok(d1.length&&d1.every(r=>r.round==='予選'&&r.start==='10:00'),'11日：予選10:00だけ（'+d1.map(r=>r.round+' '+r.start)+'）');
ok(d2.length&&d2.every(r=>r.round==='準決勝'&&r.start==='09:30'),'12日：準決勝9:30だけ（'+d2.map(r=>r.round+' '+r.start)+'）');
console.log(`\n${pass} passed, ${fail} failed`);process.exit(fail?1:0);
